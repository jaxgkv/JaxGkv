-- 4) STORAGE BUCKET BUKTI PEMBAYARAN
-- =========================================================

insert into storage.buckets (id, name, public)
values ('topup-bukti', 'topup-bukti', false)
on conflict (id) do update set public = false;

drop policy if exists "topup proof upload own folder" on storage.objects;
drop policy if exists "topup proof read own or admin" on storage.objects;

create policy "topup proof upload own folder"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'topup-bukti'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "topup proof read own or admin"
on storage.objects
for select
to authenticated
using (
  bucket_id = 'topup-bukti'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_admin()
  )
);

-- =========================================================
-- 5) APPROVE: ATOMIC + ANTI DOUBLE CREDIT
-- =========================================================

create or replace function public.approve_topup(request_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.topup_request%rowtype;
  admin_id uuid := auth.uid();
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak: admin only';
  end if;

  select * into req
  from public.topup_request
  where id = request_id
  for update;

  if not found then
    raise exception 'Request top up tidak ditemukan';
  end if;

  if req.status <> 'pending' then
    raise exception 'Request sudah diproses dengan status %', req.status;
  end if;

  update public.profiles
  set saldo = coalesce(saldo, 0) + req.nominal
  where id = req.user_id;

  if not found then
    raise exception 'Profil user tidak ditemukan';
  end if;

  update public.topup_request
  set status = 'approved',
      reviewed_by = admin_id,
      reviewed_at = now(),
      rejection_reason = null
  where id = request_id;
end;
$$;

revoke all on function public.approve_topup(bigint) from public;
grant execute on function public.approve_topup(bigint) to authenticated;

-- =========================================================
-- 6) REJECT
-- =========================================================

create or replace function public.reject_topup(request_id bigint, reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.topup_request%rowtype;
  admin_id uuid := auth.uid();
  clean_reason text := nullif(trim(reason), '');
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak: admin only';
  end if;

  if clean_reason is null then
    raise exception 'Alasan penolakan wajib diisi';
  end if;

  select * into req
  from public.topup_request
  where id = request_id
  for update;

  if not found then
    raise exception 'Request top up tidak ditemukan';
  end if;

  if req.status <> 'pending' then
    raise exception 'Request sudah diproses dengan status %', req.status;
  end if;

  update public.topup_request
  set status = 'rejected',
      rejection_reason = clean_reason,
      reviewed_by = admin_id,
      reviewed_at = now()
  where id = request_id;
end;
$$;

revoke all on function public.reject_topup(bigint, text) from public;
grant execute on function public.reject_topup(bigint, text) to authenticated;

