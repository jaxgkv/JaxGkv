-- =========================================================
-- 1) TABEL TOP UP
-- =========================================================

create table if not exists public.topup_request (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nominal bigint not null check (nominal > 0),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  proof_path text,
  rejection_reason text,
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.topup_request add column if not exists proof_path text;
alter table public.topup_request add column if not exists rejection_reason text;
alter table public.topup_request add column if not exists reviewed_by uuid references auth.users(id);
alter table public.topup_request add column if not exists reviewed_at timestamptz;

-- Jika tabel lama belum memakai constraint status, validasi di bawah.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'topup_request_status_check'
      and conrelid = 'public.topup_request'::regclass
  ) then
    alter table public.topup_request
      add constraint topup_request_status_check
      check (status in ('pending','approved','rejected'));
  end if;
end $$;

create index if not exists topup_request_user_created_idx
  on public.topup_request(user_id, created_at desc);
create index if not exists topup_request_status_created_idx
  on public.topup_request(status, created_at desc);

-- =========================================================
-- 2) HELPER ADMIN
-- =========================================================

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- =========================================================
-- 3) RLS TOP UP
-- =========================================================

alter table public.topup_request enable row level security;

drop policy if exists "topup user select own" on public.topup_request;
drop policy if exists "topup user insert own" on public.topup_request;
drop policy if exists "topup admin select all" on public.topup_request;

create policy "topup user select own"
on public.topup_request
for select
to authenticated
using (user_id = auth.uid() or public.is_admin());

create policy "topup user insert own"
on public.topup_request
for insert
to authenticated
with check (
  user_id = auth.uid()
  and status = 'pending'
);

